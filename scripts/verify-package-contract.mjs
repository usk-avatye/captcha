import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const pkgPath = path.join(root, 'packages/react/package.json');
assert.ok(existsSync(pkgPath), '독립 React SDK package.json이 있어야 한다');
const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
assert.equal(pkg.name, '@captchavatye/react');
assert.equal(pkg.version, '0.1.0');
assert.equal(pkg.private, true, '이번 단계에서는 실수로 공개 발행하지 않는다');
assert.ok(pkg.peerDependencies.react);
assert.ok(pkg.peerDependencies['react-dom']);
assert.ok(!pkg.dependencies?.react && !pkg.dependencies?.['react-dom']);
assert.equal(pkg.exports['.'].types, './dist/index.d.ts');
assert.equal(pkg.exports['.'].import, './dist/index.js');
assert.equal(pkg.exports['./style.css'], './dist/style.css');
for (const file of ['index.js', 'index.d.ts', 'style.css']) assert.ok(existsSync(path.join(root, 'packages/react/dist', file)), file);
const js = readFileSync(path.join(root, 'packages/react/dist/index.js'), 'utf8');
assert.doesNotMatch(js, /모의 포인트|10P|ReactCurrentDispatcher|__CLIENT_INTERNALS_DO_NOT_USE/);
assert.doesNotMatch(js, /localhost:5173|127\.0\.0\.1:8000/);
const css = readFileSync(path.join(root, 'packages/react/dist/style.css'), 'utf8');
assert.doesNotMatch(css, /(^|[{}])\s*(body|:root|html)\s*[{,:]/);
console.log('패키지·peer·JS·타입·CSS·배포 주소 계약 통과');
